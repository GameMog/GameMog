// Mog City: Mission 4's gallery, the door to it. The gallery itself (wagmi/gallery/gallery.js: the building, the
// statue, the portraits, the clue, the take, the certificate) loads only when asked for, so a story boot without it
// fetches none of it.
//   const G = await mount(W, opts)    the gallery mounted (gallery.js mount), its shaders compiling in the background:
//                                      G.ready resolves when they are (mount it early, e.g. on the drive to the Seaport)
//   unmount(G)                         all of it out of the scene
//   load()                             the module itself (gallery.js), for the mission to hold
// The lab: ?gallery=walk|clue|take|cert (lab/gallery.html), handled here (install, from wagmi/game.js's story list).
//
// Merging into Mission 4 (after its rounds 7-9), the notes:
//   - mount is ASYNC here (it loads gallery.js first): `const G = await mount(W, opts)`, then (ideally after
//     `await G.ready`, its shaders compiled in the background, ~35 s headless) G.show(true) where the
//     pavilion's set goes up (m4-pavilion.js), on the same spot (m4-set.js PAV / at()), so the swap is the pavilion's
//     build/show calls for these. gallery.js's own mount is synchronous once loaded (load() first to hold it).
//   - its lights live only in its own materials (wagmi/gallery/building.js): mounting it recompiles nothing of the city.
//   - opts: ui (the mission's createUI), onCheckpoint(state) / G.restore(state) / G.respawn() for the save,
//     setCertificateOwner(owner), onClue(sigil), onTake(i), onWrong(i, portrait, { strikes }), holdTraffic, and
//     interact + wrong: 'alarm' to let the mission decide what a wrong piece costs (the lab's 'fail' fails it).
//   - shared files this branch touches: wagmi/game.js (one entry, './mission/m4-gallery.js', in the story install
//     list), NOTICE (the oncyber MIT section), assets/story/*.json (regenerated by tools/story/extract.mjs: run it
//     again after the merge). No m4-*.js, ui.js or cast file is touched.
const Q = new URLSearchParams(location.search);
export const load = () => import('../gallery/gallery.js');
export async function mount(W, opts = {}) { const G = (await load()).mount(W, opts); G.ready = G.prepare(); return G; }
export function unmount(G) { G?.stop?.(); G?.dispose?.(); }
export async function install(W) {
  const mode = Q.get('gallery'); if (!mode) return;
  await (await load()).lab(W, mode);
}
