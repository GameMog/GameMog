# tools/hometown/lock_requirements.py: requirements.txt -> requirements.lock, the hash-pinned file the town-builder image
# installs with `pip install --only-binary :all: --require-hashes -r requirements.lock`. One sha256 per wheel that a
# pinned build can pick: CPython 3.14 (cp314 or the abi3 wheel) on manylinux x86_64 / aarch64 (the image) and macOS arm64
# (the dev venv). No sdists: nothing compiles at install time. Reads PyPI's JSON API (public, no account):
#   python tools/hometown/lock_requirements.py            # rewrites requirements.lock
#   python tools/hometown/lock_requirements.py --check    # exit 1 when the lock is stale against requirements.txt
import json
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
TAGS = (re.compile(r'-cp314-cp314-(manylinux_[0-9_]+_x86_64|manylinux_[0-9_]+_aarch64|macosx_\d+_\d+_arm64)'),
        re.compile(r'-cp312-abi3-(manylinux_[0-9_]+_x86_64|manylinux_[0-9_]+_aarch64|macosx_\d+_\d+_arm64)'))


def pins(path):
    out = []
    for ln in open(path):
        ln = ln.split('#', 1)[0].strip()
        if ln:
            name, _, ver = ln.partition('==')
            assert ver, 'requirements.txt pins every package with ==: %r' % ln
            out.append((name.strip().lower(), ver.strip()))
    return sorted(out)


def wheels(name, ver):
    with urllib.request.urlopen('https://pypi.org/pypi/%s/%s/json' % (name, ver), timeout=30) as r:
        d = json.load(r)
    fs = sorted((u['filename'], u['digests']['sha256']) for u in d['urls'] if u['packagetype'] == 'bdist_wheel' and any(t.search(u['filename']) for t in TAGS))
    if not fs:
        raise SystemExit('%s==%s: no cp314 / abi3 wheel for linux x86_64, linux aarch64 or macOS arm64' % (name, ver))
    return fs


def render(ps):
    lines = ['# GENERATED by tools/hometown/lock_requirements.py from requirements.txt; do not edit by hand.',
             '# pip install --only-binary :all: --require-hashes -r tools/hometown/requirements.lock',
             '# (every dependency is pinned here: shapely needs only numpy; duckdb, numpy and pillow need nothing)']
    for name, ver in ps:
        fs = wheels(name, ver)
        lines.append('%s==%s \\' % (name, ver))
        for i, (fn, h) in enumerate(fs):
            lines.append('    --hash=sha256:%s%s' % (h, '' if i == len(fs) - 1 else ' \\'))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    body = render(pins(os.path.join(HERE, 'requirements.txt')))
    lock = os.path.join(HERE, 'requirements.lock')
    if '--check' in sys.argv:
        cur = open(lock).read() if os.path.exists(lock) else ''
        print('requirements.lock is %s' % ('current' if cur == body else 'STALE'))
        sys.exit(0 if cur == body else 1)
    open(lock, 'w').write(body)
    print('wrote', lock)
